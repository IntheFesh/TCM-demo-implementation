"""药名归一。从 core/chain.py 拆出来的——core/safety_output.py 也要用它，
留在 chain 里会造成 chain ↔ safety_output 循环导入。

只做"把同一味药的不同写法归到可比对的形式"，不含任何业务判断。
"""
from __future__ import annotations

import re

_PAREN_RE = re.compile(r"[（(][^）)]*[）)]")
# 剂量写法实测有「一钱半」「钱半」「一钱五分」——原来的正则只认「数字+单位」，
# 这三种会把「半」「五分」残留在药名里，后面别名表、禁忌表、Jaccard 全部错配。
# 复合剂量「一两二钱」「三钱三分五厘」是多段「数字+单位」连写，一段一段剥。
_DOSE_RE = re.compile(
    r"(?:(?:[一二三四五六七八九十百半\d.]+(?:钱|两|分|厘|克|g|枚|片|条|支|具|个|茶匙|杯)(?:半)?)+"
    r"|钱半|两半)\s*$"
)

# 炮制前缀/后缀：同一味药在不同医家笔下写法不同（广皮=陈皮、炙草=炙甘草），
# 不归一的话药物集合比对会把同一味药算成两味，Jaccard 被系统性推高——
# 实测出现过两边实际用药大量重合、Jaccard 却算成 1.0 的情况。
# **只剥炮制字，不剥产地字。** 产地字是药名的一部分：西洋参≠洋参、川牛膝与怀牛膝
# 是两个药典品种、川木香≠木香、南/北五味子药典分列、川楝子的 canonical 名就带「川」。
# 逐字剥产地会把不同的药归成同一个名字，比不归一更糟。产地写法一律走 HERB_ALIASES
# 显式收录（下面收了 川朴/川斛/南楂/川椒/川贝 等语料里实际出现的）。
# 「生」也不剥：生地黄与熟地黄、生首乌与制首乌功用相反，同样只走别名表。
