def strip_dose_and_parens(herb: str) -> str:
    """只剥括号注释和剂量，**不动炮制前后缀**。

    单独暴露出来是因为后缀剥离对某些药名过头："天花粉"会被剥成"天花"、
    "黑顺片"会被剥成"黑顺"。配伍禁忌那边需要在剥后缀之前先查一次别名表
    （见 core/safety_output.normalize_for_incompat）。

    顺序重要：先剥括号（"旋覆花二钱（包煎）"的括号在剂量之后，
    不先剥掉的话 $ 锚点匹配不到剂量），再剥剂量。
    """
    s = _PAREN_RE.sub("", herb).strip()
    return _DOSE_RE.sub("", s).strip()


#: R64：从开源数据批量合并来的别名表。**跟 `HERB_ALIASES` 分成两份是有意的**：
#: 上面那张是逐条人工审过的（R59 建的），这张是批量合并的，两者的可信度不同，
#: 混进一个字面量里以后就分不清哪条是审过的了。查的时候人工那份**优先**。
#: 生成方式见 `offline/merge_open_sources.py --source baodian-alias`。
MERGED_ALIASES_PATH = ROOT / "data" / "standard" / "herb_aliases_merged.tsv"

_merged: dict[str, str] | None = None
_merged_lock = threading.Lock()


def merged_aliases() -> dict[str, str]:
    """惰性读那张 TSV（CLAUDE.md：加载文件的对象一律惰性初始化）。

    **文件缺失返回空表，不抛**——跟 `effect_synonyms` 那张表刻意相反：
    那张表缺了会让一条验证规则恒假且没人发现，这张表缺了只是少认几个别名，
    归一照常работает，退化是可见的（`scripts/check_herb_coverage.py` 的数字会涨）。
    """
    global _merged
    if _merged is None:
        with _merged_lock:
            if _merged is None:
                table: dict[str, str] = {}
                if MERGED_ALIASES_PATH.exists():
                    for raw in MERGED_ALIASES_PATH.read_text(encoding="utf-8").splitlines():
                        line = raw.strip()
                        if not line or line.startswith("#"):
                            continue
                        cols = line.split("\t")
                        if len(cols) < 2 or cols[0] == "别名":
                            continue
                        table[cols[0].strip()] = cols[1].strip()
                _merged = table
    return _merged


def reset_merged_aliases_for_tests() -> None:
    global _merged
    _merged = None


def _alias(s: str) -> str | None:
    """查别名表：原样查一次，剥掉后缀再查一次。

    **人工审过的那份先查**（`HERB_ALIASES`），合并来的那份后查——同一个写法
    两边都有时以人工那份为准。
    """
    stripped = _HERB_SUFFIX.sub("", s).strip()
    merged = merged_aliases()
    return (HERB_ALIASES.get(s) or merged.get(s)
            or HERB_ALIASES.get(stripped) or merged.get(stripped))


def normalize_herb(herb: str) -> str:
    """把药名归一到可比对的形式：剥括号注释、剥剂量、查别名表、剥炮制前后缀。

    前缀是**逐字**剥、每剥一个字查一次别名表，不是一次性全剥完再查。原来一次性
    贪婪剥完（「炒广皮」→「皮」）只剩一个字就退回原串，别名表从头到尾没机会命中
    ——实测「炒广皮」「广皮炭」「云苓块」都因此归不到陈皮/茯苓，两位医家写法不同
    就被算成两味药，Jaccard 被系统性推高，正是这个模块要防的事。
    """
    s = strip_dose_and_parens(herb)
    if not s:
        return ""
    core = s
    while True:
        hit = _alias(core)
        if hit:
            return hit
        # 剥到只剩两个字就停：再剥就是「生姜」→「姜」这种剥过头
        if len(core) > 2 and core[0] in _AFFIX_CHARS:
            core = core[1:]
            continue
        break
    stripped = _HERB_SUFFIX.sub("", core).strip()
    return stripped if len(stripped) >= 2 else core


def normalized_herb_set(herbs: list[str] | None) -> set[str]:
    """一张方的可比对药物集合：逐味归一、丢掉归一后为空的。分歧度的 Jaccard
    （core/chain.py）和噪声地板 ε（offline/estimate_epsilon.py）都从这里取——
    ε 是分歧度的对照基准，"怎么把一张方变成集合"两边必须是同一个定义，
    否则 ε 就不再跟它要对照的那个数可比。"""
    return {h for h in (normalize_herb(x) for x in (herbs or [])) if h}


# ---------- 君臣佐使分层（R1 降 ε 用）----------
#
# 君臣 = 这个证的核心判断，佐使 = 针对兼夹症状的加减。分层比对的目的是把
# "核心判断不一致"和"加减用药不同"分开报：实测同一条主诉重复跑三次，叶天士
# 的君臣骨架（半夏/延胡索/炙甘草/茯苓）三次全在，变的全是佐使（神曲/黄连/
# 桑叶青皮），而主诉里根本没有食积、热象、肺卫的症状——把两者混成一个数，
# 这个"核心稳定、加减发散"的事实就看不见了，只能看到一个 0.53 说不清含义。
CORE_ROLES = ("君", "臣")
ADJUNCT_ROLES = ("佐", "使")


def role_partitioned_herb_sets(herb_items) -> dict:
    """把一张方的逐味药条目按君臣/佐使切成两个可比对集合。

    入参是 `HerbItem` 形状的条目列表（只用到 `.name` 和 `.role`），不是扁平药名
    列表——`role` 只存在于条目上，`core.schemas._S3Base._derive_flat_fields` 把
    条目压成 `.herbs` 时就把它丢了。S3 结论那边取条目请走
    `s3.selected_herb_items`（占位符过滤只在 core/schemas.py 做一处）。

    归一走 `normalize_herb`，跟 `normalized_herb_set` 同一把尺子——分层的数要跟
    `herb_jaccard` 放在一起读，两边"怎么把一张方变成集合"必须是同一个定义。
    西药也照 `herb_jaccard` 的做法剔掉（`split_western_drugs` 的同一条理由：
    只有张锡纯用西药，算进去会把跨学派分歧系统性推高，而那个推高是假的）。

    `role=None` 的药**不进任何一层**，只计进 `n_unroled`：硬塞进某一类会让指标
    的含义变得不可解释（"这个 core_jaccard 里有几味药其实不知道是不是君臣"）。
    这些药并没有从统计里消失——`herb_jaccard` 不看 role，照旧把它们算在内。
    """
    core: set[str] = set()
    adjunct: set[str] = set()
    n_unroled = 0
    n_items = 0
    for item in herb_items or []:
        if is_western_drug(item.name):
            continue
        name = normalize_herb(item.name)
        if not name:
            continue
        n_items += 1
        if item.role in CORE_ROLES:
            core.add(name)
        elif item.role in ADJUNCT_ROLES:
            adjunct.add(name)
        else:
            n_unroled += 1
    return {"core": core, "adjunct": adjunct, "n_unroled": n_unroled, "n_items": n_items}


# ---------- 西药识别（A2 张锡纯「衷中参西」用）----------
#
# 跟 HERB_ALIASES 回答的不是同一个问题，所以是另一张表、不合并：
# HERB_ALIASES 答的是"这两个写法是不是同一味药"，这里答的是"这个名字是不是
# 西药"——合成一张表，以后改一边看不出会不会连带影响另一边（CLAUDE.md 对
# core/safety.py 那张危重词表用的是同一条例外理由）。
#
# **词表从原书真实文本挖出来，不是凭印象编的。** 张锡纯自己会写「西药阿斯匹林」
# 这种前缀，把 books/584-医学衷中参西录.txt（GB18030）按「西药X」扫一遍就是
# 最可靠的来源。实测结果推翻了两个想当然的写法：
#   阿司匹林 0 次 / 阿斯匹林 136 次；白布圣 0 次 / 百布圣 19 次。
# 现代写法（阿司匹林）仍然收进来，是为了将来接现代医案，不是这本书里有。
WESTERN_DRUGS: tuple[str, ...] = (
    "阿斯匹林", "阿司匹林",   # aspirin，前者是原书写法（136 次），后者是现代写法
    "百布圣", "白布圣",        # pepsin，前者是原书写法（19 次）
    "金鸡纳霜",                # 15 次
    "规尼涅", "规泥涅",        # quinine，原书两种写法各 1 次
    "安知歇貌林",              # antipyrine，3 次
    "灰锰氧",                  # 高锰酸钾，3 次
    "臭剥",                    # 溴化钾，2 次
    "几阿苏",                  # creosote，1 次
    "留苦",                    # 原书标了「西药留苦四钱」，2 次
    "硫酸镁",                  # 原书标了「西药硫酸镁二钱」
    "麦角",                    # ergot，原书「西药中有麦角」
    "磺碘",                    # 碘制剂，2 次
)

# 刻意不收的几个词，以及为什么——收进来会把中药误判成西药，而误判的代价是
# 一味真中药被从 herb_jaccard 里剔掉，直接污染分歧度这个主指标，比漏掉一味
# 西药更糟：
#   盐酸/硫酸（单独）：原书 8 次「盐酸」里有 5 次是「鸡内金……含有稀盐酸」，
#                      说的是中药的化学成分，不是在开西药。只收完整的「硫酸镁」。
#   碘（单字）：单字词太容易撞进别的名字，只收原书实际出现的「磺碘」。
#   樟脑、薄荷脑：都是正经中药材/中药成分（原书「薄荷之成分，含有薄荷脑」）。
#   缬草：中药材里也有这个名字，虽然原书写过「西药中之缬草」。
_WESTERN_PREFIX = "西药"


def is_western_drug(name: str) -> bool:
    """判断一个**药物条目**（不是整段原文）是不是西药。

    刻意在原始字符串上匹配，不先过 normalize_herb——那个函数是给中药名设计的，
    对西药名有害：实测「盐酸规尼涅」会被剥成「酸规尼涅」（`盐` 在 _AFFIX_CHARS
    里，本意是处理「盐炒杜仲」），「阿斯匹林一瓦」的「瓦」也不在剂量正则里。

    只在药物条目上用，不要拿去扫原文段落：原文里「鸡内金含有稀盐酸」这类成分
    描述会被误判，而条目层面的「稀盐酸」本来就该算西药，两者风险不同。
    """
    if not name:
        return False
    s = name.strip()
    # 原书自己打的标记：「西药阿斯匹林」「西药几阿苏六分」——前缀命中就够，
    # 不必逐个把音译词都收进上面的表（那本来也收不全）。
    if s.startswith(_WESTERN_PREFIX):
        return True
    return any(w in s for w in WESTERN_DRUGS)


def split_western_drugs(names: list[str]) -> tuple[list[str], list[str]]:
    """把一个药物列表拆成 (中药, 西药)，保持各自的原始顺序与写法。

    **全项目唯一的拆分实现**：S0 抽取（offline/extract_cases.py）和 S3 开方
    （core/chain.py）两个边界都调它。prompt 里也写了同样的要求，但 prompt 是
    约束不是保证——模型照样可能把阿斯匹林塞进 herbs，代码这一层必须兜住，
    否则西药会混进 herb_jaccard 把跨学派分歧系统性推高，而那个推高是假的。
    """
    herbs, western = [], []
    for n in names or []:
        (western if is_western_drug(n) else herbs).append(n)
    return herbs, western
