_DOSE_UNIT_TO_GRAMS: dict[str, float | None] = {
    "g": 1.0,
    # 市制换算：1 斤=500g、16 两/斤、1 两=10 钱、1 钱=10 分（1979 年统一后的
    # 中药计量标准），跟 M2 任务描述给定的换算比例一致。
    "钱": 3.125,
    "两": 31.25,
    "分": 0.3125,
    # 计数单位，没有统一克重（一枚附子和一枚酸枣仁完全不是一回事），
    # 没法换算成克，只能返回 None——调用方要把 None 当"这条没法做剂量检查"
    # 处理，不能当成 0："0g" 意味着"剂量是 0"，None 意味着"这个单位没法换算"，
    # 两者是不同的信号。
    "枚": None,
    "片": None,
}


def to_grams(dose: float | None, unit: str) -> float | None:
    """把 HerbItem 的 (dose, dose_unit) 换算成克，用来对着 DOSE_LIMITS（克为准）比。"""
    if dose is None:
        return None
    factor = _DOSE_UNIT_TO_GRAMS[unit]
    return None if factor is None else dose * factor


def check_dose_limits(items: list[HerbItem]) -> list[DoseViolation]:
    """逐味药核对是否超过 DOSE_LIMITS 里的上限。

    剂量缺失（dose is None）或单位没法换算成克（枚/片）的条目直接跳过，
    不算超限——"没写剂量"不是"剂量超限"，是另一种信号，跟 HerbItem 文档
    字符串里"缺失一律 None、不填默认值"是同一条纪律。

    查表顺序：先用调用方给的原始写法查一次，查不到再用 normalize_herb 归一后
    的名字查一次——跟 normalize_for_incompat 的顺序同一个理由。有些写法
    （"黑顺片"）normalize_herb 会剥过头（剥成"黑顺"），DOSE_LIMITS 里已经把
    这类写法显式收录成独立键，原始写法这一步就能命中，不需要依赖归一。
    "生半夏"与"半夏"、"生附子"与"附子"在表里是不同的两条限量，归一会把
    "生半夏"剥成"半夏"（normalize_herb 保留了"生"前缀，不会剥，但仍要显式
    收录两条——归一之后落到同一个键会让严格的生品限量被宽松的制品限量盖掉，
    先查原始写法能保住这条区分）。
    """
    violations = []
    for item in items:
        grams = to_grams(item.dose, item.dose_unit)
        if grams is None:
            continue
        entry = DOSE_LIMITS.get(item.name) or DOSE_LIMITS.get(normalize_herb(item.name))
        if entry is None:
            continue
        limit_g, reason = entry
        if grams > limit_g:
            violations.append(DoseViolation(
                herb=item.name, dose=item.dose, unit=item.dose_unit,
                limit_g=limit_g, reason=reason,
            ))
    return violations


def check_required_decoction(items: list[HerbItem]) -> list[str]:
    """返回"该有特殊煎法但没标对"的药名列表（原始写法，不是归一名——跟处方
    展示保持一致）。"没标对"包含两种情况：完全没填（None）和填了但不是
    要求的那种——后者比空白更危险（一个写着"后下"的附子看起来"已经处理过"，
    实际上该先煎的没先煎，比空白字段更容易被忽略）。

    查表顺序原始写法优先、查不到再查归一名，理由同 check_dose_limits：
    "生半夏"和"半夏"在这张表里都要求先煎，但如果表里只收一个、归一把另一个
    盖掉了，少收的那条就会被静默漏检。
    """
    missing = []
    for item in items:
        required = REQUIRED_DECOCTION.get(item.name) or REQUIRED_DECOCTION.get(normalize_herb(item.name))
        if required and item.decoction != required:
            missing.append(item.name)
    return missing


def check_toxic_herbs(items: list[HerbItem]) -> list[str]:
    """标出方里含有毒/大毒药材的药名（原始写法）。警告级，不拦——医家对毒性
    药材的使用本就需要专业判断（附子救急回阳时的常规剂量范围恰好就贴着
    DOSE_LIMITS 的上限），系统只负责让这件事在界面上可见，不替医家做决定。
    """
    found = []
    for item in items:
        if item.name in TOXIC_HERBS or normalize_herb(item.name) in TOXIC_HERBS:
            found.append(item.name)
    return found


def format_dose_violations(violations: list[DoseViolation]) -> str:
    """把剂量超限列表拼成给 S3 重生成用的提示文本。"""
    return "、".join(
        f"{v.herb}（{v.dose}{v.unit}，超过常用上限 {v.limit_g}g：{v.reason}）"
        for v in violations
    )


def format_blocking_issues(safety: FormulaSafety) -> str:
    """把一个候选方**拦截级**问题（十八反十九畏 + 剂量超限）拼成给 S3 重生成用
    的提示文本。寒热不一致/缺煎法/毒性提示是警告级，不进这段文字——重开是
    冲着"必须改"去的，警告级问题混进去会让模型分不清哪些是硬要求。
    """
    parts = []
    if safety.incompatible:
        parts.append(f"存在中药十八反十九畏配伍禁忌：{format_conflicts(safety.incompatible)}")
    if safety.dose_violations:
        parts.append(f"以下药味剂量超出安全上限：{format_dose_violations(safety.dose_violations)}")
    return "；".join(parts)


def assess_formula_safety(syndrome: str, candidate: FormulaCandidate) -> FormulaSafety:
    """给一个候选方跑全部 X2 输出侧安全检查，返回汇总结果。**唯一的组装点**——
    run_physician 给每个候选方调一次这个函数，不是把 check_incompatible /
    check_thermal_consistency / check_dose_limits / check_required_decoction /
    check_toxic_herbs 五个检查散着调、自己攒结果，那样以后加第六个检查会有
    两处要记得同步。

    西药条目（herb_items 里混进的阿斯匹林一类）不参与任何一项检查——十八反/
    寒热/剂量/煎法/毒性表全部是中药知识，喂一个西药名进去要么查不到（无害但
    浪费），要么在极端情况下误判。跟 S3Syndrome.herbs（M1 派生字段）用的是
    同一条过滤规则（is_western_drug），两处必须一致——这是为什么这里也调
    core.herbs 的同一个判断，不另写一套字面匹配。
    """
    kept_items = [item for item in candidate.herb_items if not is_western_drug(item.name)]
    names = [item.name for item in kept_items]
    return FormulaSafety(
        incompatible=check_incompatible(names),
        thermal_warning=check_thermal_consistency(syndrome, names),
        dose_violations=check_dose_limits(kept_items),
        decoction_missing=check_required_decoction(kept_items),
        toxic_herbs=check_toxic_herbs(kept_items),
    )
